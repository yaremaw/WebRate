export function getItemBySlug(slug: string): RateItem | undefined {
  return items.find((item) => item.slug === slug);
}

export function getTrendingItems(limit = 6): RateItem[] {
  return [...items]
    .sort((a, b) => b.ratingCount - a.ratingCount)
    .slice(0, limit);
}

export function getControversialItems(limit = 4): RateItem[] {
  return [...items]
    .sort((a, b) => b.controversyScore - a.controversyScore)
    .slice(0, limit);
}

export function getRelatedItems(item: RateItem, limit = 3): RateItem[] {
  return items
    .filter((i) => i.id !== item.id && i.category === item.category)
    .slice(0, limit);
}
